/**
 * Creates the forum's content types and seeds a board.
 *
 * Topics are this app's own content type. Replies and votes are the two types
 * the schema plugin's comments preset creates, `comments` and `comment_votes`,
 * and every one of them is written through the same admin content route as a
 * topic.
 *
 * Safe to run more than once. Applying an existing schema is accepted, a
 * preset whose types already exist answers 409 and is taken as done, and
 * seeding stops if the forum already has topics.
 */
import {
	LyeveError,
	applySchemas,
	createContent,
	listContent,
	lyeveFromEnv
} from '../src/lib/lyeve/index.ts';

const client = lyeveFromEnv();

const TOPICS = 'forum_topics';

await applySchemas(client, [
	{
		name: TOPICS,
		display_name: 'Forum topics',
		fields: [
			{ name: 'title', field_type: 'text', required: true },
			{ name: 'slug', field_type: 'text', required: true, indexed: true },
			{ name: 'body', field_type: 'text' },
			{ name: 'category', field_type: 'text', indexed: true },
			{ name: 'author_name', field_type: 'text' },
			{ name: 'pinned', field_type: 'boolean' },
			{ name: 'locked', field_type: 'boolean' }
		]
	}
]);
console.log('content type ready');

// The preset refuses, creating nothing, when any type it would create already
// exists. On a second run that is the expected answer, not a failure.
try {
	await client.request('admin', '/api/admin/schemas/presets/comments', { method: 'POST' });
	console.log('comments preset applied: comments, comment_votes');
} catch (err) {
	if (!(err instanceof LyeveError) || err.status !== 409) throw err;
	console.log('comments preset already applied');
}

if ((await listContent(client, TOPICS, { limit: 25 })).length > 0) {
	console.log('topics already seeded, nothing to do');
	process.exit(0);
}

