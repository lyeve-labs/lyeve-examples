interface CommentInput {
	topicId: string;
	body: string;
	author_name: string;
	author_email: string;
	status: 'pending' | 'approved';
	parent?: string;
}

/**
 * Creates one reply. A seeded board needs approved replies to read as a board,
 * so the seed chooses the status. A visitor's reply is always written pending.
 */
async function createComment(input: CommentInput): Promise<string> {
	const created = await createContent(client, {
		schema: 'comments',
		slug: `forum-reply-${crypto.randomUUID()}`,
		title: `Reply to ${input.topicId}`,
		body: {
			target_schema: TOPICS,
			target_id: input.topicId,
			parent: input.parent,
			author_name: input.author_name,
			author_email: input.author_email,
			body: input.body,
			status: input.status
		}
	});
	return created.id;
}

async function seedReplies(topicId: string, replies: SeedReply[], parent?: string) {
	for (const reply of replies) {
		const id = await createComment({
			topicId,
			parent,
			author_name: reply.author,
			author_email: reply.email,
			body: reply.body,
			status: reply.pending ? 'pending' : 'approved'
		});

		for (const voter of VOTERS.slice(0, reply.upvotes ?? 0)) {
			await createContent(client, {
				schema: 'comment_votes',
				slug: `forum-vote-${id}-${voter}`,
				title: 'Forum vote',
				body: { comment: id, voter_key: voter, value: 1 }
			});
		}

		if (reply.children) await seedReplies(topicId, reply.children, id);
	}
}

let replyCount = 0;
let pendingCount = 0;

for (const topic of topics) {
	const { id } = await createContent(client, {
		schema: TOPICS,
		slug: topic.slug,
		title: topic.title,
		body: {
			slug: topic.slug,
			body: topic.body,
			category: topic.category,
			author_name: topic.author,
			pinned: topic.pinned ?? false,
			locked: topic.locked ?? false
		}
	});

	// A reply names the topic by entry id rather than slug, so renaming a topic
	// cannot orphan its replies. Nothing enforces the link: target_id is a
	// text column with no foreign key.
	await seedReplies(id, topic.replies);

	const count = (function total(replies: SeedReply[]): number {
		return replies.reduce((n, reply) => {
			if (reply.pending) pendingCount++;
			return n + 1 + total(reply.children ?? []);
		}, 0);
	})(topic.replies);
	replyCount += count;
}

console.log(
	`seeded ${topics.length} topics and ${replyCount} replies, ${pendingCount} of them waiting for a moderator`
);
